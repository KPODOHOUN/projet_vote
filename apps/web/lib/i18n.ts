export type MessageKey = keyof (typeof messages)["fr"];

export function translate(locale: Locale, key: MessageKey): string {
  return messages[locale][key] ?? messages[defaultLocale][key];
}

export function translateVars(locale: Locale, key: MessageKey, vars: Record<string, string | number>): string {
  return translate(locale, key).replace(/\{(\w+)\}/g, (match, name: string) =>
    name in vars ? String(vars[name]) : match
  );
}

export function publicEventDateLocale(locale: Locale): string {
  return locale === "en" ? "en-GB" : "fr-FR";
}

const eventStatusLabels: Record<string, { fr: string; en: string }> = {
  DRAFT: { fr: "En préparation", en: "Getting ready" },
  ACTIVE: { fr: "En ligne", en: "Live" },
  CLOSED: { fr: "Terminé", en: "Ended" },
  ARCHIVED: { fr: "Archivé", en: "Archived" }
};

const userRoleLabels: Record<string, { fr: string; en: string }> = {
  ORGANIZER_OWNER: { fr: "Responsable", en: "Owner" },
  ORGANIZER_STAFF: { fr: "Membre", en: "Member" },
  PLATFORM_ADMIN: { fr: "Administrateur", en: "Administrator" }
};

export function formatEventStatus(status: string, isEn: boolean): string {
  const entry = eventStatusLabels[status];
  if (!entry) return status;
  return isEn ? entry.en : entry.fr;
}

export function formatUserRole(role: string, isEn: boolean): string {
  const entry = userRoleLabels[role];
  if (!entry) return isEn ? "Member" : "Membre";
  return isEn ? entry.en : entry.fr;
}
